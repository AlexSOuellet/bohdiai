/**
 * Scans blocks/** and widgets/** for meta.ts files, imports each one,
 * and emits lib/blocks-manifest.generated.ts and lib/widgets-manifest.generated.ts.
 *
 * Run via: npm run build:manifests
 * Wired into prebuild and predev so it runs automatically.
 */

import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const ROOT = resolve(process.cwd());

// ─── File discovery ───────────────────────────────────────────────────────────

function findMetaFiles(dir) {
  const results = [];
  if (!statSync(dir, { throwIfNoEntry: false })) return results;

  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const fullPath = join(dir, entry.name);
    if (entry.isDirectory()) {
      results.push(...findMetaFiles(fullPath));
    } else if (entry.name === 'meta.ts') {
      results.push(fullPath);
    }
  }

  return results;
}

// ─── Manifest generation ──────────────────────────────────────────────────────

function serializeToTs(value) {
  return JSON.stringify(value, null, 2);
}

function writeManifest(outputPath, typeName, importType, items) {
  const itemsJson = `[\n${items.map((item) => `  ${serializeToTs(item).replace(/\n/g, '\n  ')}`).join(',\n')}\n]`;

  const content = [
    `// AUTO-GENERATED by scripts/build-manifests.mjs`,
    `// Run \`npm run build:manifests\` to regenerate after adding or removing blocks/widgets.`,
    `// Do not edit manually.`,
    ``,
    `import type { ${importType} } from './blocks';`,
    ``,
    `export const ${typeName}_MANIFEST: ${importType}[] = ${itemsJson} satisfies ${importType}[];`,
    ``,
    `export const ${typeName}_MAP: Readonly<Record<string, ${importType}>> = Object.fromEntries(`,
    `  ${typeName}_MANIFEST.map((item) => [item.key, item])`,
    `);`,
    ``,
  ].join('\n');

  writeFileSync(outputPath, content, 'utf8');
  console.log(`  wrote ${outputPath.replace(ROOT, '.')}`);
}

// ─── Main ─────────────────────────────────────────────────────────────────────

async function main() {
  const blockMetaFiles = findMetaFiles(join(ROOT, 'blocks'));
  const widgetMetaFiles = findMetaFiles(join(ROOT, 'widgets'));

  console.log(
    `build-manifests: found ${blockMetaFiles.length} block(s), ${widgetMetaFiles.length} widget(s)`,
  );

  const blocks = [];
  for (const file of blockMetaFiles) {
    const mod = await import(pathToFileURL(file).href);
    const meta = mod.default ?? mod.meta;
    if (meta === undefined) {
      console.warn(`  warn: ${file} has no default export — skipping`);
      continue;
    }
    blocks.push(meta);
    console.log(`  block: ${meta.key}`);
  }

  const widgets = [];
  for (const file of widgetMetaFiles) {
    const mod = await import(pathToFileURL(file).href);
    const meta = mod.default ?? mod.meta;
    if (meta === undefined) {
      console.warn(`  warn: ${file} has no default export — skipping`);
      continue;
    }
    widgets.push(meta);
    console.log(`  widget: ${meta.key}`);
  }

  writeManifest(join(ROOT, 'lib', 'blocks-manifest.generated.ts'), 'BLOCKS', 'BlockMeta', blocks);

  writeManifest(
    join(ROOT, 'lib', 'widgets-manifest.generated.ts'),
    'WIDGETS',
    'WidgetMeta',
    widgets,
  );

  console.log('build-manifests: done');
}

main().catch((err) => {
  console.error('build-manifests failed:', err);
  process.exit(1);
});
